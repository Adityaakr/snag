/**
 * File classes (BUILD_PROMPT 6.4.1). Path rules apply in this order: lockfile, generated/vendored, test, ci,
 * migration, docs, config, source. Rust `#[cfg(test)]` modules are detected per unit, not here.
 */
import type { FilterReason, Language, UnitKind } from '@remit/core';
import { type AttributeRule, attributeFor } from './gitattributes.js';
import { matchAny } from './glob.js';

export interface FileClass {
  kind: UnitKind;
  language: Language;
  filtered?: FilterReason;
}

export interface ClassifyContext {
  /** Parsed `.gitattributes` rules from the head tree. */
  attributes?: readonly AttributeRule[];
  /** The first lines of the head version, used to spot `@generated` headers. */
  headText?: string;
  /** True when the diff marks the file as binary. */
  binary?: boolean;
}

