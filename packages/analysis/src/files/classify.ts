const EXT_LANG: Record<string, Language> = {
  ts: 'ts',
  mts: 'ts',
  cts: 'ts',
  tsx: 'tsx',
  js: 'js',
  mjs: 'js',
  cjs: 'js',
  jsx: 'js',
  py: 'py',
  pyi: 'py',
  rs: 'rs',
};

/** Language from the file extension; `other` for anything tree-sitter does not parse here. */
export function languageOf(path: string): Language {
  const ext = /\.([A-Za-z0-9]+)$/.exec(path)?.[1]?.toLowerCase() ?? '';
  return EXT_LANG[ext] ?? 'other';
}

/** True when the first lines carry a common generated-code marker. */
export function hasGeneratedHeader(text: string): boolean {
  const head = text.split('\n', 8).join('\n');
  return /@generated\b|\bDO NOT EDIT\b|\bauto-?generated\b|\bCode generated by\b/i.test(head);
}

function basename(path: string): string {
  return path.slice(path.lastIndexOf('/') + 1);
}

/** Classifies one file by path, attributes and header. */
export function classifyFile(path: string, ctx: ClassifyContext = {}): FileClass {
  const language = languageOf(path);
  if (ctx.binary) return { kind: 'binary', language, filtered: 'binary' };
  if (LOCKFILES.includes(basename(path))) return { kind: 'lockfile', language, filtered: 'lockfile' };

  const attrs = ctx.attributes ?? [];
  const vendoredAttr = attributeFor(attrs, path, 'linguist-vendored');
  const generatedAttr = attributeFor(attrs, path, 'linguist-generated');
  if (vendoredAttr === true || (vendoredAttr !== false && matchAny(path, VENDORED))) {
    return { kind: 'vendored', language, filtered: 'vendored' };
  }
  if (
    generatedAttr === true ||
    (generatedAttr !== false &&
      (matchAny(path, GENERATED) || (ctx.headText !== undefined && hasGeneratedHeader(ctx.headText))))
  ) {
    return { kind: 'generated', language, filtered: 'generated' };
  }

  if (matchAny(path, TESTS)) return { kind: 'test', language };
  if (matchAny(path, CI)) return { kind: 'ci', language };
  if (matchAny(path, MIGRATIONS)) return { kind: 'migration', language };
  if (matchAny(path, DOCS)) return { kind: 'docs', language };
  if (matchAny(path, CONFIG)) return { kind: 'config', language };
  if (matchAny(path, BUILD)) return { kind: 'build', language };
  if (matchAny(path, ASSETS)) return { kind: 'asset', language };
  return { kind: 'source', language };
}
